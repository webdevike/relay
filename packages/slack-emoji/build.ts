// Regenerates src/data.ts from iamcal's emoji-datasource (the shortcode set Slack itself uses):
// every short name and alias to its emoji. `bun build.ts` after bumping VERSION.
import { writeFileSync } from "node:fs";
import { join } from "node:path";

const VERSION = "16.0.0";
const url = `https://unpkg.com/emoji-datasource@${VERSION}/emoji.json`;
const res = await fetch(url);
if (!res.ok) throw new Error(`${url}: ${String(res.status)}`);
const rows = (await res.json()) as Array<{ unified: string; short_names: string[] }>;

const toChars = (unified: string): string => String.fromCodePoint(...unified.split("-").map((hex) => parseInt(hex, 16)));
const entries = new Map<string, string>();
for (const row of rows) for (const name of row.short_names) if (!entries.has(name)) entries.set(name, toChars(row.unified));
const sorted = [...entries].sort(([a], [b]) => a.localeCompare(b));

const body = sorted.map(([name, chars]) => `  ${JSON.stringify(name)}: ${JSON.stringify(chars)},`).join("\n");
writeFileSync(
  join(import.meta.dir, "src", "data.ts"),
  `// Generated by build.ts from emoji-datasource ${VERSION} (MIT, iamcal): Slack's shortcodes. Do not edit.\nexport const SLACK_EMOJI: Readonly<Record<string, string>> = {\n${body}\n};\n`,
);
console.log(`${String(sorted.length)} short names`);
