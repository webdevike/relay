/** The original's three seed kinds: `visual`, `text` and `idea`. */
export type SeedKind = "visual" | "text" | "idea";

/** The pool each request kind rolls from: a name or a text is a `text` seed, a concept an `idea`, a look a `visual`. */
export const seedKindOf = (kind: Kind): SeedKind =>
  kind === "visual-direction" ? "visual" : kind === "concept" ? "idea" : "text";

const pick = <A>(items: ReadonlyArray<A>, rng: Rng): A => items[Math.floor(rng() * items.length)]!;

const method = (rng: Rng) => {
  const families = Object.values(METHOD_FAMILIES);
  return pick(pick(families, rng), rng);
};

/** One seed, as `roll` in `seed.py`: one value per axis of the kind, plus setting, region and an anchor. Axis order is the original's. */
export const roll = (kind: SeedKind, rng: Rng = systemRng): Readonly<Record<string, string>> => {
  const out: Record<string, string> = {};
  if (kind === "visual") {
    out["method"] = method(rng);
    for (const [axis, items] of Object.entries(VISUAL)) out[axis] = pick(items, rng);
  } else {
    for (const [axis, items] of Object.entries(kind === "text" ? TEXT : IDEA))
      out[axis] = pick(items, rng);
  }
  if (kind === "visual") {
    out["verb"] = pick(IDEA["verb"]!, rng);
    out["scale"] = pick(IDEA["scale"]!, rng);
  }
  out["setting"] = pick(SETTING, rng);
  out["region"] = pick(REGION, rng);
  out["anchor"] = kind === "visual" && rng() < 0.5 ? pick(NO_ANCHOR, rng) : pick(ANCHOR, rng);
  return out;
};

/** A seed as the lines the model reads (`axis: value`, as `seed.py` prints). */
export const render = (seed: Readonly<Record<string, string>>): string =>
  Object.entries(seed)
    .map(([axis, value]) => `${axis}: ${value}`)
    .join("\n");
