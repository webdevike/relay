// Bundles the live view page (vnc/viewer.ts + @novnc/novnc) into one self-contained HTML string at
// src/vnc/viewerHtml.ts, so the app ships noVNC with no CDN or asset fetch. Run with Bun after
// changing viewer.ts or bumping @novnc/novnc: `pnpm --filter @relay/mobile vnc:build`.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const novncDir = dirname(dirname(createRequire(import.meta.url).resolve("@novnc/novnc")));
const novnc = JSON.parse(readFileSync(join(novncDir, "package.json"), "utf8"));

const result = await Bun.build({
  entrypoints: [join(here, "viewer.ts")],
  target: "browser",
  // noVNC uses top-level await (codec probing), so the page is an inline module script.
  format: "esm",
  minify: true,
});
if (!result.success) {
  for (const log of result.logs) console.error(log);
  process.exit(1);
}
const [bundle] = result.outputs;
// Inline in a <script>: nothing in the bundle may close the element early.
const script = (await bundle.text()).replaceAll("</script", "<\\/script");

const html = `<!doctype html>
<html>
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no,viewport-fit=cover">
<style>
html, body { margin: 0; height: 100%; background: #000; overflow: hidden; overscroll-behavior: none; touch-action: none; -webkit-user-select: none; user-select: none; -webkit-touch-callout: none; }
#screen { position: fixed; inset: 0; }
</style>
</head>
<body>
<div id="screen"></div>
<script type="module">${script}</script>
</body>
</html>
`;

const out = join(here, "..", "src", "vnc", "viewerHtml.ts");
writeFileSync(
  out,
  `// Generated by vnc/build.mjs from vnc/viewer.ts and @novnc/novnc ${novnc.version} (MPL-2.0). Do not edit.\n` +
    `export const VIEWER_HTML = ${JSON.stringify(html)};\n`,
);
console.log(`wrote ${out} (${html.length} bytes, noVNC ${novnc.version})`);
