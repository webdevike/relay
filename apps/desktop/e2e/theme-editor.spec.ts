import * as fs from 'node:fs'
import * as path from 'node:path'
import { test, expect } from './fixtures'

test.use({ startOnChat: false, colorScheme: 'dark' })
test('full-width theme editor edits colors and previews interactive controls', async ({ app, shell, configDir }) => {
  await app.evaluate(({ BaseWindow }) => BaseWindow.getAllWindows()[0]!.setContentSize(1440, 900))
  await shell.locator('[data-testid=nav-setting]').click()
  await shell.locator('.eva-theme-mode-row label').filter({ hasText: 'Dark' }).click()
  const panel = shell.locator('[data-testid=panel-toggle]:visible')
  if (await panel.getAttribute('aria-pressed') === 'true') await panel.click()
  const editor = shell.getByTestId('theme-editor')
  await expect(editor).toBeVisible()
  const preview = shell.getByTestId('theme-preview')
  await expect(preview).toBeVisible()
  await preview.getByPlaceholder('Type to preview').fill('Theme preview works')
  await expect(preview.getByPlaceholder('Type to preview')).toHaveValue('Theme preview works')
  const toggle = preview.getByRole('switch', { name: 'Switch', exact: true })
  const previous = await toggle.isChecked()
  await toggle.click()
  if (previous) await expect(toggle).not.toBeChecked()
  else await expect(toggle).toBeChecked()
  await shell.getByTestId('theme-property-search').fill('background')
  const color = shell.getByRole('textbox', { name: 'background', exact: true })
  await color.fill('#223344')
  await color.press('Tab')
  await expect.poll(() => shell.evaluate(() => getComputedStyle(document.documentElement).getPropertyValue('--eva-c-background').trim())).toBe('#223344')
  const file = path.join(configDir, 'theme.json')
  await expect.poll(() => fs.readFileSync(file, 'utf8')).toContain('#223344')
  await shell.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect.poll(() => shell.evaluate(() => getComputedStyle(document.documentElement).getPropertyValue('--eva-c-background').trim())).not.toBe('#223344')
  await shell.getByTestId('theme-property-search').clear()
  await preview.getByRole('heading', { name: 'Preview', exact: true }).click()
  await shell.screenshot({ path: path.join('..', '..', 'proof', 'ux-parity', 'electron-theme-page.png') })
})
