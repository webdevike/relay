/** The icon for a Tabler name (`list-check`, `IconListCheck`, `List Check`); a plain circle when unknown. */
export function stepIcon(name: string | undefined): Icon {
  const key = (name ?? '')
    .trim()
    .replace(/^Icon(?=[A-Z])/, '')
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .toLowerCase()
    .replace(/^icon-/, '')
    .replace(/[\s_]+/g, '-')
  return STEP_ICONS[key] ?? IconCircle
}
